export type QueueCase = {
  caseId: string;
  sessionId: string;
  caseStatus: CaseStatus;
  language: PatientLanguage;
  primaryComplaint: string | null;
  complaintCount: number;
  topSeverity: string | null;
  unreviewedSignals: number;
  documentCount: number;
  documentsProcessing: number;
  demoFlag: boolean;
  createdAt: Date;
  completedAt: Date | null;
  startedAt: Date | null;
  doctorName: string | null;
};

/**
 * Queue list for doctor/hospital consoles, derived from real state:
 * complaints, safety signals, and documents are all counted live.
 */
export async function listQueueCases(client: PoolClient): Promise<QueueCase[]> {
  const result = await client.query(`
    SELECT s.id, s.case_id, s.case_status, s.language, s.demo_flag, s.created_at, s.completed_at,
           con.started_at AS consult_started_at, c.display_name AS doctor_name,
           (SELECT co.complaint_text FROM complaints co
             WHERE co.session_id = s.id AND co.status = 'ACTIVE'
             ORDER BY co.position LIMIT 1) AS primary_complaint,
           (SELECT COUNT(*)::int FROM complaints co
             WHERE co.session_id = s.id AND co.status = 'ACTIVE') AS complaint_count,
           (SELECT co.severity FROM complaints co
             WHERE co.session_id = s.id AND co.status = 'ACTIVE' AND co.severity IS NOT NULL
             ORDER BY CASE co.severity WHEN 'MILD' THEN 1 WHEN 'MODERATE' THEN 2
                       WHEN 'SEVERE' THEN 3 ELSE 4 END DESC LIMIT 1) AS top_severity,
           (SELECT COUNT(*)::int FROM safety_signals sg
             WHERE sg.session_id = s.id AND sg.status = 'UNREVIEWED') AS unreviewed_signals,
           (SELECT COUNT(*)::int FROM documents d WHERE d.session_id = s.id) AS document_count,
           (SELECT COUNT(*)::int FROM documents d WHERE d.session_id = s.id
             AND d.ocr_status IN ('PENDING', 'PROCESSING')
             OR d.session_id = s.id AND d.extraction_status = 'PROCESSING') AS documents_processing
      FROM patient_sessions s
      LEFT JOIN consultations con ON con.session_id = s.id AND con.status = 'IN_PROGRESS'
      LEFT JOIN staff c ON c.id = con.doctor_id
     WHERE s.case_status IN ('AWAITING_REVIEW', 'URGENT_REVIEW', 'IN_CONSULTATION', 'IN_PROGRESS', 'NEW')
     ORDER BY
       CASE WHEN s.case_status = 'URGENT_REVIEW' THEN 0
            WHEN s.case_status = 'AWAITING_REVIEW' THEN 1
            WHEN s.case_status = 'IN_CONSULTATION' THEN 2 ELSE 3 END,
       s.created_at`);
  return result.rows.map((row) => ({
    caseId: row.case_id as string,
    sessionId: row.id as string,
    caseStatus: row.case_status as CaseStatus,
    language: row.language as PatientLanguage,
    primaryComplaint: row.primary_complaint as string | null,
    complaintCount: row.complaint_count as number,
    topSeverity: row.top_severity as string | null,
    unreviewedSignals: row.unreviewed_signals as number,
    documentCount: row.document_count as number,
    documentsProcessing: row.documents_processing as number,
    demoFlag: row.demo_flag as boolean,
    createdAt: row.created_at as Date,
    completedAt: row.completed_at as Date | null,
    startedAt: row.consult_started_at as Date | null,
    doctorName: row.doctor_name as string | null,
  }));
}

/** Operational funnel counts (hospital console) — all live SQL aggregates. */
export async function getFunnelCounts(client: PoolClient) {
  const result = await client.query(`
    SELECT
      (SELECT COUNT(*)::int FROM patient_sessions WHERE case_status = 'NEW' OR case_status = 'IN_PROGRESS') AS kiosk_intake,
      (SELECT COUNT(*)::int FROM patient_sessions WHERE case_status = 'AWAITING_REVIEW' OR case_status = 'URGENT_REVIEW') AS pre_consultation,
      (SELECT COUNT(*)::int FROM documents WHERE ocr_status IN ('PENDING','PROCESSING')
         OR extraction_status = 'PROCESSING') AS document_processing,
      (SELECT COUNT(*)::int FROM patient_sessions WHERE case_status = 'IN_CONSULTATION') AS in_consultation,
      (SELECT COUNT(*)::int FROM patient_sessions WHERE case_status = 'COMPLETED') AS completed,
      (SELECT COUNT(*)::int FROM patient_sessions WHERE case_status = 'URGENT_REVIEW') AS urgent,
      (SELECT COALESCE(AVG(EXTRACT(EPOCH FROM (now() - created_at)))::bigint, 0)
         FROM patient_sessions WHERE case_status IN ('AWAITING_REVIEW','URGENT_REVIEW'))::int AS avg_wait_seconds`);
  return result.rows[0] as {
    kiosk_intake: number;
    pre_consultation: number;
    document_processing: number;
    in_consultation: number;
    completed: number;
    urgent: number;
    avg_wait_seconds: number;
  };
}
